// Run against `npm run dev` to recapture genuine engine-rendered showcase media.
import {chromium} from 'playwright';
import {writeFileSync,mkdirSync} from 'node:fs';
import {gzipSync} from 'node:zlib';
const output=new URL('../showcase/',import.meta.url);
mkdirSync(output,{recursive:true});
const browser=await chromium.launch({args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1280,height:720}});
page.on('pageerror',e=>{throw e;});
await page.goto('http://localhost:5173');
await page.waitForTimeout(500);
const handle=await page.evaluateHandle(async()=>{
 const {createEngine,ConstantClock}=await import('/node_modules/@clockwyrks/simple-2d/dist/index.js');
 const {game,BACKGROUND}=await import('/src/game.ts');
 const canvas=document.createElement('canvas');canvas.style.cssText='position:fixed;inset:0;width:100vw;height:100vh;z-index:100';document.body.append(canvas);
 const engine=createEngine({canvas,width:1280,height:720,game,background:BACKGROUND,clock:new ConstantClock(1000/30)});await engine.initialize();
 const d=engine.debug;
 engine.apply(s=>d.setScreen(d.generateMine(d.setWorldSize(d.reset(s),'quick')),'in-mine'));
 for(const [track,tier] of [['fuel',4],['hull',4],['drill',3],['cargo',3],['jetpack',1],['scanner',3]])engine.apply(s=>d.setTier(s,track,tier));
 engine.apply(s=>d.setFuel(s,342));engine.apply(s=>d.setHull(s,292));engine.apply(s=>d.setCredits(s,2460));engine.apply(s=>d.setCargo(s,'cuprite',6));engine.apply(s=>d.setCargo(s,'argenite',4));
 for(let r=79;r<=90;r++)engine.apply(s=>d.setTile(s,16,r,'tunnel'));
 for(let c=10;c<=20;c++)engine.apply(s=>d.setTile(s,c,86,'tunnel'));
 for(let c=11;c<=15;c++)engine.apply(s=>d.setTile(s,c,94,'tunnel'));
 for(let r=86;r<=94;r++)engine.apply(s=>d.setTile(s,11,r,'tunnel'));
 for(let c=18;c<=20;c++)engine.apply(s=>d.setOreTile(s,c,89,'cuprite'));
 for(let c=12;c<=15;c++)engine.apply(s=>d.setOreTile(s,c,93,'argenite'));
 for(let r=91;r<=95;r++)engine.apply(s=>d.setOreTile(s,16,r,'argenite'));
 engine.apply(s=>d.setOreTile(s,20,92,'verdite'));
 engine.apply(s=>d.setMaterialTile(s,20,94,'resonite'));
 engine.apply(s=>d.setTile(s,21,90,'gas'));
 engine.apply(s=>d.setMinerPosition(s,16*80+12,91*80-72));
 await engine.advance(1);
 return {engine,canvas};
});
await handle.evaluate(async({engine})=>{engine.startRecording();document.dispatchEvent(new KeyboardEvent('keydown',{code:'KeyS'}));await engine.advance(70);document.dispatchEvent(new KeyboardEvent('keyup',{code:'KeyS'}));});
await page.screenshot({path:new URL('rockbed.png',output).pathname});
await handle.evaluate(async({engine})=>{document.dispatchEvent(new KeyboardEvent('keydown',{code:'Space'}));await engine.advance(40);document.dispatchEvent(new KeyboardEvent('keyup',{code:'Space'}));await engine.advance(10);});
const recording=await handle.evaluate(({engine})=>engine.stopRecording());
writeFileSync(new URL('descent.json.gz',output),gzipSync(JSON.stringify(recording),{level:9}));
await handle.evaluate(async({engine})=>{const d=engine.debug;engine.apply(s=>d.setMinerVelocity(d.setMinerPosition(s,1420,8),0,0));engine.apply(s=>d.setRocketInstalled(s,4));engine.apply(s=>d.setPanel(s,null));await engine.advance(100);});
await page.screenshot({path:new URL('camp.png',output).pathname});
await handle.evaluate(async({engine})=>{const d=engine.debug;engine.apply(s=>d.setPanel(s,'launch-pad'));await engine.advance(1);});
await page.screenshot({path:new URL('fabrication.png',output).pathname});
await handle.evaluate(({engine})=>engine.destroy());
await browser.close();
